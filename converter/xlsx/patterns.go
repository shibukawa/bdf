package xlsx

import (
	"bytes"
	"fmt"
	"image"
	"image/color"
	"image/png"
	"math"

	"github.com/shibukawa/bdf"
)

// Pattern fills repeat an 8×8 bitmap (a set bit is the pattern color, a
// clear one the background) at one bitmap pixel per screen pixel.
var patternBits = map[string][8]byte{
	"gray0625":        {0x80, 0x00, 0x00, 0x00, 0x08, 0x00, 0x00, 0x00},
	"gray125":         {0x88, 0x00, 0x22, 0x00, 0x88, 0x00, 0x22, 0x00},
	"lightGray":       {0x88, 0x22, 0x88, 0x22, 0x88, 0x22, 0x88, 0x22},
	"mediumGray":      {0xAA, 0x55, 0xAA, 0x55, 0xAA, 0x55, 0xAA, 0x55},
	"darkGray":        {0x77, 0xDD, 0x77, 0xDD, 0x77, 0xDD, 0x77, 0xDD},
	"darkHorizontal":  {0xFF, 0xFF, 0x00, 0x00, 0xFF, 0xFF, 0x00, 0x00},
	"lightHorizontal": {0xFF, 0x00, 0x00, 0x00, 0xFF, 0x00, 0x00, 0x00},
	"darkVertical":    {0xCC, 0xCC, 0xCC, 0xCC, 0xCC, 0xCC, 0xCC, 0xCC},
	"lightVertical":   {0x88, 0x88, 0x88, 0x88, 0x88, 0x88, 0x88, 0x88},
	"darkDown":        {0xCC, 0x66, 0x33, 0x99, 0xCC, 0x66, 0x33, 0x99},
	"darkUp":          {0x33, 0x66, 0xCC, 0x99, 0x33, 0x66, 0xCC, 0x99},
	"lightDown":       {0x88, 0x44, 0x22, 0x11, 0x88, 0x44, 0x22, 0x11},
	"lightUp":         {0x11, 0x22, 0x44, 0x88, 0x11, 0x22, 0x44, 0x88},
	"darkGrid":        {0xFF, 0xFF, 0xCC, 0xCC, 0xFF, 0xFF, 0xCC, 0xCC},
	"lightGrid":       {0xFF, 0x88, 0x88, 0x88, 0xFF, 0x88, 0x88, 0x88},
	"darkTrellis":     {0x99, 0xFF, 0x66, 0xFF, 0x99, 0xFF, 0x66, 0xFF},
	"lightTrellis":    {0x88, 0x55, 0x22, 0x55, 0x88, 0x55, 0x22, 0x55},
}

// patternImage returns the image of a pattern fill in two colors (stored
// once per pattern and colors).
func (c *converter) patternImage(name string, fg, bg rgb) bdf.Hash {
	key := fmt.Sprintf("%s|%v|%v", name, fg, bg)
	if h, ok := c.patterns[key]; ok {
		return h
	}
	bits, ok := patternBits[name]
	if !ok {
		c.warnOnce("pattern:"+name, "pattern fill %s is drawn as 50%% gray", name)
		bits = patternBits["mediumGray"]
	}
	q := func(v float64) uint8 { return uint8(math.Round(clamp01(v) * 255)) }
	f := color.NRGBA{q(fg.R), q(fg.G), q(fg.B), 255}
	b := color.NRGBA{q(bg.R), q(bg.G), q(bg.B), 255}
	img := image.NewNRGBA(image.Rect(0, 0, 8, 8))
	for y := 0; y < 8; y++ {
		for x := 0; x < 8; x++ {
			if bits[y]&(0x80>>x) != 0 {
				img.SetNRGBA(x, y, f)
			} else {
				img.SetNRGBA(x, y, b)
			}
		}
	}
	var buf bytes.Buffer
	png.Encode(&buf, img)
	h := c.doc.AddImage(buf.Bytes())
	c.patterns[key] = h
	return h
}
