// appendDigit adds a filled outline, keeping the inner contours of digits.
func appendDigit(p *bdf.Path, digit byte, x, baseline, scale float32) {
	if digit > 9 {
		return
	}
	d := digitOutlines[digit]
	i := 0
	point := func() (float32, float32) {
		xp, yp := x+float32(float32(d.args[i])*scale), baseline-float32(float32(d.args[i+1])*scale)
		i += 2
		return xp, yp
	}
	for _, v := range []byte(d.verbs) {
		switch v {
		case 'M':
			xp, yp := point()
			p.MoveTo(xp, yp)
		case 'L':
			xp, yp := point()
			p.LineTo(xp, yp)
		case 'Q':
			cx, cy := point()
			xp, yp := point()
			p.QuadTo(cx, cy, xp, yp)
		case 'Z':
			p.Close()
		}
	}
}
